def build_display_name_map(people: PeopleFile) -> dict[str, str]:
    """Build a mapping from ``participant_id`` → display name.

    Returns ``short_name`` if set, otherwise ``participant_id``.
    """
    names: dict[str, str] = {}
    for pid, entry in people.participants.items():
        if entry.editable.short_name:
            names[pid] = entry.editable.short_name
        else:
            names[pid] = pid
    return names


# ---------------------------------------------------------------------------
# Name extraction from metadata
# ---------------------------------------------------------------------------

# Labels that are generic placeholders, not real names.
_GENERIC_LABEL_RE = re.compile(
    r"^(speaker\s*[a-z0-9]|SPEAKER_\d+|unknown|narrator)$",
    re.IGNORECASE,
)

# A dial-in caller's label is their phone number, masked or not —
# "+44 7700 ****23", "+1 (555) 010-9876". Teams and Zoom both write these.
# Never a name: it is a digit string, and an unmasked one is PII that would
# otherwise land in people.yaml as somebody's full_name.
_MASKED_PHONE_RE = re.compile(r"^\+?[\d\s()*#•·.\-]{6,}$")


def is_generic_label(label: str) -> bool:
    """Is this speaker label a placeholder rather than a person's name?

    True for Whisper/diarisation placeholders ("Speaker A", "SPEAKER_00",
    "Unknown"), bare numbers, and phone numbers, masked or whole. Every
    surface that turns a label into a name asks this one question — the
    people file, the one-transcript-per-session choice, the splitter gate —
    so a new placeholder shape is added here and nowhere else.
    """
    stripped = label.strip()
    if not stripped:
        return True
    if _GENERIC_LABEL_RE.match(stripped):
        return True
    if stripped.isdigit():
        return True
    if _MASKED_PHONE_RE.match(stripped) and any(ch.isdigit() or ch == "*" for ch in stripped):
        return True
    return False


def extract_names_from_labels(
    transcripts: list[FullTranscript],
    *,
    platform_only: bool = False,
) -> dict[str, str]:
    """Extract probable real names from ``speaker_label`` metadata.

    Teams/VTT transcripts often have real names as speaker labels
    (e.g. "Sarah Jones" instead of "Speaker A").  Returns
    ``{participant_code: name}`` for labels that look like real names —
    keyed by each participant's speaker code when the segments carry one, so
    every named participant in a two-participant session gets a name, not
    only the session's primary one; a transcript without codes keys on its
    ``participant_id`` as before.

    With ``platform_only``, only labels written by a transcript FILE count
    (``PLATFORM_TRANSCRIPT_SOURCES``): the platform's own record of who
    spoke, which ``auto_populate_names`` lets beat the LLM's guess.
    """
    names: dict[str, str] = {}
    for transcript in transcripts:
        # Per participant code, how often each label appears.
        label_counts: dict[str, dict[str, int]] = {}
        for seg in transcript.segments:
            if seg.speaker_role != SpeakerRole.PARTICIPANT or not seg.speaker_label:
                continue
            if platform_only and seg.source not in PLATFORM_TRANSCRIPT_SOURCES:
                continue
            pid = seg.speaker_code or transcript.participant_id
            counts = label_counts.setdefault(pid, {})
            counts[seg.speaker_label] = counts.get(seg.speaker_label, 0) + 1
        for pid, counts in label_counts.items():
            # Pick the most frequent label.
            label = max(counts, key=counts.get)  # type: ignore[arg-type]
            # Skip placeholders, numbers and phone labels.
            if is_generic_label(label):
                continue
            names[pid] = label.strip()
    return names


# ---------------------------------------------------------------------------
# Auto-populate editable fields from extracted data
# ---------------------------------------------------------------------------


def auto_populate_names(
    people: PeopleFile,
    speaker_infos: dict[str, SpeakerInfo],
    label_names: dict[str, str],
    *,
    platform_names: dict[str, str] | None = None,
) -> None:
    """Pre-populate empty ``full_name``/``role`` fields from extracted data.

    Only fills fields that are currently empty — never overwrites user edits.
    Priority: platform-transcript name > LLM-extracted name > other label.

    ``platform_names`` is what the platform itself wrote against each
    participant's turns (``extract_names_from_labels(..., platform_only=True)``).
    It is the one source that is not a guess, so it beats the LLM's
    ``person_name`` — measured on the Talismanic study, the model's "Pri" had
    been overwriting Teams' own "Priya Nair". Participants only: moderators
    are not named from labels in this slice (every session's moderator is
    ``m1``, so the last session processed would win — see
    ``docs/design-cloud-import-transcripts.md`` §0b). ``label_names`` keeps
    its old place for labels of unknown provenance, so the LLM still beats a
    generic label.

    For a shared moderator code the ``speaker_infos`` entry is whichever
    session the caller iterated last (``pipeline.py``, the ``pid_speaker_info``
    loop), including one whose ``person_name`` is empty — so the name on
    ``m1`` is an accident of session order (storyboard frame F2).  Under route
    C (``docs/design-people.md`` §E decision 1, corrected 1 Oct 2026) an LLM
    hearing becomes a hint on an unidentified slot and never fills a name;
    only a platform label proposes one.  The never-overwrite rule survives as
    "never touch a confirmed row".

    Mutates *people* in place.
    """
    platform_names = platform_names or {}
    for pid, entry in people.participants.items():
        ed = entry.editable

        # full_name: platform label (participants) > LLM > other label metadata
        if not ed.full_name:
            info = speaker_infos.get(pid)
            if pid.startswith("p") and pid in platform_names:
                ed.full_name = platform_names[pid]
            elif info and info.person_name:
                ed.full_name = info.person_name
            elif pid in label_names:
                ed.full_name = label_names[pid]

        # role (job title): LLM only
        if not ed.role:
            info = speaker_infos.get(pid)
            if info and info.job_title:
                ed.role = info.job_title


# ---------------------------------------------------------------------------
# Short name suggestion
# ---------------------------------------------------------------------------


def _extract_given_name(full_name: str) -> str:
    """Extract the likely given name from a full name.

    Handles three special cases using pre-loaded data files:

    1. **CJK ideographic names** (Chinese/Japanese/Korean characters without
       spaces) — the full name is already short enough, returned as-is.
    2. **Honorific prefixes** ("Dr.", "Prof.", etc.) — stripped before
       extracting the first token.
    3. **Family-name-first cultures** (Chinese, Korean, Vietnamese, Japanese,
       Hungarian) — when the first token matches a known family name, the
       *second* token is returned instead.

    Falls back to the first whitespace-delimited token for all other names.
    """
    # CJK names without spaces are already short — use as-is.
    if _CJK_RE.search(full_name) and " " not in full_name:
        return full_name

    # Strip honorific prefix ("Dr. Sarah Jones" → "Sarah Jones").
    stripped = _strip_honorific(full_name)
    parts = stripped.split()
    if not parts:
        return full_name

    # Family-name-first detection: if the first token is a known family
    # name from a family-first culture, take the second token (the given
    # name) instead.
    if len(parts) >= 2 and parts[0].lower() in _FAMILY_FIRST_SURNAMES:
        return parts[1]

    return parts[0]


def suggest_short_names(people: PeopleFile) -> None:
    """Auto-suggest ``short_name`` for participants missing one.

    Extracts the likely given name from ``full_name``, handling honorifics,
    CJK names, and family-name-first conventions.  When two participants
    share a given name, disambiguates with the last-name initial
    (e.g. "Sarah J." vs "Sarah K.").

    Only sets ``short_name`` on entries where it is currently empty.
    Mutates *people* in place.
    """
    # Collect candidates: entries that have full_name but no short_name.
    candidates: dict[str, str] = {}  # pid -> given_name
    for pid, entry in people.participants.items():
        if entry.editable.full_name and not entry.editable.short_name:
            candidates[pid] = _extract_given_name(entry.editable.full_name)

    if not candidates:
        return

    # Detect given-name collisions.
    first_counts: dict[str, int] = {}
    for given in candidates.values():
        first_counts[given] = first_counts.get(given, 0) + 1

    # Assign short names.
    for pid, given in candidates.items():
        if first_counts[given] > 1:
            # Disambiguate: append last-name initial if available.
            parts = people.participants[pid].editable.full_name.split()
            if len(parts) >= 2:
                short = f"{given} {parts[-1][0]}."
            else:
                short = given
        else:
            short = given
        people.participants[pid].editable.short_name = short


# ---------------------------------------------------------------------------
# Per-session moderator and observer names
# ---------------------------------------------------------------------------
#
# Moderator and observer codes restart in every session (``m1`` is "the first
# moderator *in this session*"), so ``people.yaml``, keyed by code, can hold
# only one name for all of them — the last session processed wins. The serve
# DB already keeps one speaker row per (session, code); this file is what lets
# it name each one from its own session. Participants are not in it: their
# codes are study-wide and ``people.yaml`` names them correctly.
#
# A step towards route C (``docs/design-people.md`` §H H9), not route C itself:
# no identities, no ``m?``. Decided by the owner on 3 Oct 2026 as the weekend
# fix; the identity layer builds on the per-session rows this fills.

