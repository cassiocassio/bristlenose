def compute_participant_stats(
    sessions: list[InputSession],
    transcripts: list[FullTranscript],
) -> dict[str, PersonComputed]:
    """Compute per-participant stats from session and transcript data.

    Returns a dict keyed by ``participant_id``.

    **Known limitation — moderator/observer codes collide across sessions.**
    Participant codes are globally numbered, but ``assign_speaker_codes()``
    resets its moderator/observer counters per session, so every session's
    first moderator is ``m1``.  This dict is keyed by code alone, so in a
    multi-session study the last session's ``m1`` overwrites the earlier ones
    and only one survives into ``people.yaml``.  Collisions are collected and
    reported in a single WARNING rather than passing silently.

    The fix is **not** a ``(session, code)`` rekey of this file — that was
    considered and rejected (``docs/design-transcript-speaker-editing-roadmap.md``
    §11c, 25 Aug 2026).  Decided 1 Oct 2026: a session's moderator slot lives
    on ``session_speakers`` and is ``null`` until a platform label proposes an
    identity or a researcher picks one; the per-session ``m1`` token stays as a
    within-session tag, and this file is retired as a store.  See
    ``docs/design-people.md`` §E decision 1 (corrected) and §H H9.  Phase 1
    built the slot map in the serve database, fed by ``session_speaker_stats``
    and ``session_speaker_names``; this file keeps the limitation until Phase
    5 retires it, and
    ``tests/test_people.py::test_multi_session_moderator_codes_collide_and_are_warned``
    pins the limitation, not a desired end state.
    """
    transcript_map: dict[str, FullTranscript] = {
        t.session_id: t for t in transcripts
    }

    stats: dict[str, PersonComputed] = {}
    total_words_all = 0
    # Speaker codes seen in more than one session — see the collision note below.
    code_sessions: dict[str, list[str]] = {}

    for session in sessions:
        sid = session.session_id
        transcript = transcript_map.get(sid)

        if transcript is None:
            # No transcript — create a placeholder for the primary participant
            pid = session.participant_id
            stats[pid] = PersonComputed(
                participant_id=pid,
                session_id=sid,
                session_date=session.session_date,
                duration_seconds=0.0,
                words_spoken=0,
                pct_words=0.0,
                pct_time_speaking=0.0,
                source_file=session.files[0].path.name if session.files else "",
            )
            continue

        # Group ALL segments by speaker_code, creating per-code entries
        code_words: dict[str, int] = {}
        code_seconds: dict[str, float] = {}
        for seg in transcript.segments:
            code = seg.speaker_code or session.participant_id
            if code not in code_words:
                code_words[code] = 0
                code_seconds[code] = 0.0
            code_words[code] += len(seg.text.split())
            code_seconds[code] += max(0.0, seg.end_time - seg.start_time)

        for code, words in code_words.items():
            if code.startswith("p"):
                total_words_all += words
            # Speaker code reused across sessions — the earlier entry is about
            # to be overwritten and its stats lost.  Collected here, reported
            # once after the loop so a 10-session study doesn't print nine
            # near-identical warnings at the researcher.  See the docstring:
            # only codes that reset per session (m/o) reach this in practice.
            prior = stats.get(code)
            if prior is not None and prior.session_id != sid:
                seen = code_sessions.setdefault(code, [prior.session_id])
                seen.append(sid)
            stats[code] = PersonComputed(
                participant_id=code,
                session_id=sid,
                session_date=transcript.session_date,
                duration_seconds=transcript.duration_seconds,
                words_spoken=words,
                pct_words=0.0,  # filled in second pass
                pct_time_speaking=(
                    round(code_seconds[code] / transcript.duration_seconds * 100, 1)
                    if transcript.duration_seconds > 0
                    else 0.0
                ),
                source_file=transcript.source_file,
            )

    if code_sessions:
        detail = "; ".join(
            f"{code} in {', '.join(sids)} (only {sids[-1]} survives)"
            for code, sids in sorted(code_sessions.items())
        )
        logger.warning(
            "Speaker code reused across sessions: %s. people.yaml holds one entry "
            "per code, so the earlier sessions' stats are discarded and one name "
            "covers every session that carries the code. Moderator and observer "
            "codes restart at 1 each session; per-session moderator identity is "
            "built in the serve database (route C Phase 1), not in this file — see "
            "docs/design-people.md §H H9.",
            detail,
        )

    # Second pass: compute pct_words relative to total across all participants.
    # Only count participant codes (pN) for the denominator.
    if total_words_all > 0:
        for computed in stats.values():
            if computed.participant_id.startswith("p"):
                computed.pct_words = round(
                    computed.words_spoken / total_words_all * 100, 1
                )

    return stats


