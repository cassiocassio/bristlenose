#!/bin/bash
# Fail in seconds, not after a 7-minute Swift suite, when a checkout cannot run build-all.sh.
#
# WHY THIS EXISTS (17 Nov 2026)
# -----------------------------
# The Background Assets signed store build failed five times in a row on environment, each
# time minutes into build-all.sh and each time for something the tree could have been asked
# up front: no `pip-licenses` (the `[release]` extra), a checkout path containing a space
# (the licence inventory cannot read a venv under one, and /new-branch worktrees live at
# `bristlenose_branch <name>`), no `GeneratedBuildInfo.swift` (gitignored, so a fresh clone
# lacks it), no `frontend/node_modules`. Each cost a restart. The checks below are exactly
# those, each with the command that fixes it.
#
# THE SIGNED/AD-HOC SPLIT
# -----------------------
# `--signed` adds the two checks build-all.sh only enforces on a real signing identity
# (step 2b: the supply-chain inventory). An ad-hoc dev build skips that step, so a spaced
# worktree path is fine for it and must not be refused.
#
# WHAT THIS DOES NOT CHECK (so nobody reads a green as more than it is)
# ---------------------------------------------------------------------
# THIRD-PARTY-BINARIES.md freshness: the inventory reads .venv-sidecar, which step 2 of
# build-all.sh re-resolves from PyPI, so it cannot be known before that step. Run
# `.venv/bin/python scripts/generate-third-party-binaries.py --check` yourself first.
# Profiles, identities and disk space are step 1's own business.
#
# Usage: check-build-env.sh [--signed] [ROOT]      (ROOT defaults to this script's checkout)
# Exit:  0 every check passed · 1 at least one failed (each failure names its fix)
set -uo pipefail

SIGNED=0
if [ "${1:-}" = "--signed" ]; then SIGNED=1; shift; fi
case "${1:-}" in --*) echo "usage: check-build-env.sh [--signed] [ROOT]  (flag goes first)" >&2; exit 2 ;; esac
[ "$#" -le 1 ] || { echo "usage: check-build-env.sh [--signed] [ROOT]" >&2; exit 2; }
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT="${1:-$(cd "$SCRIPT_DIR/../.." && pwd)}"
ROOT="$(cd "$ROOT" 2>/dev/null && pwd)" || { echo "✗ checkout: no such directory: ${1:-}" >&2; exit 1; }

FAILS=0
ok()   { echo "  ✓ $1"; }
bad()  { echo "  ✗ $1" >&2; shift; for l in "$@"; do echo "      $l" >&2; done; FAILS=$((FAILS+1)); }

# 1. Whitespace in the path. [[:space:]] covers space and tab; a U+00A0 would slip through,
# which is accepted (the layout that causes this is `bristlenose_branch <name>`, a plain space).
if [ "$SIGNED" = 1 ]; then
    case "$ROOT" in
        *[[:space:]]*)
            bad "checkout path contains whitespace: $ROOT" \
                "pip-licenses cannot read a venv under such a path, so a signed build fails at step 2b." \
                "Use a space-free checkout: see desktop/gotchas.md 'A signed build needs a space-free checkout'." ;;
        *) ok "checkout path has no whitespace" ;;
    esac

    # 2. The release extra. Imported with the project's own interpreter, as build-all.sh does.
    if [ -x "$ROOT/.venv/bin/python" ] \
        && "$ROOT/.venv/bin/python" -c "import importlib.util, sys; sys.exit(0 if importlib.util.find_spec('piplicenses') else 1)" 2>/dev/null; then
        ok "pip-licenses installed in .venv"
    else
        if [ -x "$ROOT/.venv/bin/python" ]; then
            bad "pip-licenses is not installed in $ROOT/.venv" \
                "  cd \"$ROOT\" && .venv/bin/pip install -e '.[release]'"
        else
            bad "there is no $ROOT/.venv" \
                "  cd \"$ROOT\" && python3.12 -m venv .venv && .venv/bin/pip install -U pip && .venv/bin/pip install -e '.[dev,serve,release]'"
        fi
    fi
fi

# 3. Frontend dependencies (build-sidecar.sh needs them and fails with this same fix, late).
if [ -d "$ROOT/frontend/node_modules" ]; then
    ok "frontend/node_modules present"
else
    bad "frontend/node_modules is missing" \
        "  cd \"$ROOT/frontend\" && npm ci --legacy-peer-deps"
fi

# 4. Tools the sidecar and extension builds shell out to.
for tool in node npm; do
    if command -v "$tool" >/dev/null 2>&1; then ok "$tool on PATH"; else bad "$tool is not on PATH"; fi
done

# 5. GeneratedBuildInfo.swift: gitignored, regenerated by every Xcode build, absent from a
# fresh checkout (the first Swift compile there fails with "cannot find 'GeneratedBuildInfo'").
# Generated ONLY WHEN ABSENT: the generator stamps the build date, so it would rewrite the file
# on every run and race a concurrent Xcode build (both write the same .tmp), and a read-only
# tree holding a good file would fail. Generated by THAT checkout's own script, never the copy
# beside this one (a foreign ROOT must not write into the checkout this file lives in), with
# SRCROOT/CONFIGURATION unset (inherited from an Xcode phase they redirect the output file).
INFO="$ROOT/desktop/Bristlenose/Bristlenose/GeneratedBuildInfo.swift"
GEN="$ROOT/desktop/scripts/generate-build-info.sh"
if [ -f "$INFO" ]; then
    ok "GeneratedBuildInfo.swift present"
elif [ ! -f "$GEN" ]; then
    bad "generate-build-info.sh not found at $GEN" "  is $ROOT a Bristlenose checkout?"
elif ( unset SRCROOT CONFIGURATION; bash "$GEN" >/dev/null 2>&1 ) && [ -f "$INFO" ]; then
    ok "GeneratedBuildInfo.swift generated"
else
    bad "GeneratedBuildInfo.swift could not be generated" \
        "  bash \"$GEN\""
fi

if [ "$FAILS" -ne 0 ]; then
    echo "build environment: $FAILS check(s) failed" >&2
    exit 1
fi
echo "build environment: ok"
