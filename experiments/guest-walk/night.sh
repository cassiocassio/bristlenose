#!/bin/bash
# night.sh <run-name> — one night: clone the frozen base, boot it, walk, throw it away.
#
# The base (walk27-base) is Cirrus's macOS 27 *vanilla* image plus only the tart
# guest agent (prep-base.sh) and the two privacy grants a person gave it once.
# Every night is a fresh clone of it, so nothing a walk does survives to the next.
# Env: BASE (default walk27-base), PROVIDER (ollama for a real run), OUT, CHANGE.
set -uo pipefail
RUN="${1:?run name}"
HERE="$(cd "$(dirname "$0")" && pwd)"
export TART_HOME=/Volumes/Iona/tart
TART=${TART_BIN:-$HOME/Applications/tart.app/Contents/MacOS/tart}
BASE="${BASE:-walk27-base}"
export GUEST="walk-$RUN"
export OUT="${OUT:-/private/tmp/bn-walk}"

# Only two macOS guests may run at once (Virtualization.framework refuses a third).
running=$($TART list --format json 2>/dev/null | python3 -c 'import json,sys; print(sum(1 for v in json.load(sys.stdin) if v.get("State")=="running"))')
[ "${running:-0}" -lt 2 ] || { echo "two guests already running"; exit 75; }

# KEEP=1 leaves the clone running after the walk, to explore by hand.
cleanup() { [ "${KEEP:-0}" = 1 ] && return; $TART stop "$GUEST" >/dev/null 2>&1; $TART delete "$GUEST" >/dev/null 2>&1; }
trap cleanup EXIT
$TART clone "$BASE" "$GUEST" || exit 1
(cd / && nohup $TART run "$GUEST" --dir="walk:/Volumes/Iona/tart/share/bn-walk:ro" >/dev/null 2>&1 </dev/null &)
for i in $(seq 1 60); do "$HERE/g.sh" true 2>/dev/null && break; sleep 3; done
"$HERE/g.sh" true || { echo "guest never answered"; exit 1; }
"$HERE/g.sh" sh -c 'sw_vers -productVersion; csrutil status' | tr '\n' ' '; echo
# The screens fixture lives on the share (regenerated by fixture/make.sh); copy it in.
"$HERE/g.sh" sh -c 'rm -rf ~/Documents/screens-project && cp -R "/Volumes/My Shared Files/walk/screens-project" ~/Documents/'
"$HERE/walk.sh" "$RUN"
