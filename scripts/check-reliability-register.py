#!/usr/bin/env python3
"""The felt-reliability register's score is computed from its rows, never typed.

`docs/reliability-register.md` lists every known way Bristlenose makes a
researcher doubt it: an action that does not land solid, immediate, honest and
final. Each row records how often a researcher meets the failure and what it
costs them; its priority follows from those two cells by a fixed rule, so a
row's rank is a fact about the row and not an argument about it.

The burndown is the reason the register exists, and a burndown that is typed by
hand drifts: a number that lives in two places is wrong in one of them. So the
score block and each row's priority are derived here, and the check fails when
the document disagrees with its own table.

Checks:
1. Every row parses: `R<n>` id, a known class, frequency, cost and status.
2. Ids are unique (a row keeps its id for life, closed or not).
3. Each row's `P` cell equals the rule's verdict for its frequency and cost.
4. A `fixed` row names a commit (7+ hex) — closing a row is a claim with an
   anchor, never a bare tick.
5. The block between the score markers equals the score computed now.

Deliberately NOT checked: whether a row's frequency, cost or status is *true*.
That is a judgement against the running product, and the register's own
"Keeping it true" section says how it is made.

Usage:
    scripts/check-reliability-register.py            # check (exit 1 on drift)
    scripts/check-reliability-register.py --write    # rewrite P cells + score
    scripts/check-reliability-register.py --record   # --write, and log today's
                                                     # totals in the burndown

Exit 0: the register agrees with itself. Exit 1: it does not (each problem is
printed). Hard by default, per docs/testing/soft-gates.json: deterministic,
sub-second, and the fix is `--write`.
"""

from __future__ import annotations

import datetime as _dt
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTER = ROOT / "docs" / "reliability-register.md"

CLASSES = (
    "LOSS", "FAKE", "SILENT", "WEDGE", "SPEND", "STALE", "DEAD", "JUMP", "PROMPT", "CRASH",
)
FREQS = ("every", "most", "some", "rare")
COSTS = ("high", "med", "low")
# `open`: understood and reproducible from the code. `unproven`: the code path
# is read but the failure has not been made to happen — reproduce before fixing.
# `decision`: waiting on an owner call, not on engineering. `fixed <sha>`.
# `withdrawn`: on investigation, not a failure (the row stays, so the reasoning
# that made it look like one is not repeated).
STATUSES = ("open", "unproven", "decision", "fixed", "withdrawn")
OPEN_STATUSES = ("open", "unproven", "decision")

# | R12 | what the researcher meets | CLASS | freq | cost | P1 | status | where |
ROW = re.compile(
    r"^\|\s*(R\d+)\s*\|(?P<meets>[^|]*)\|\s*(?P<cls>[A-Z/ ]+?)\s*\|\s*(?P<freq>\w+)\s*\|"
    r"\s*(?P<cost>\w+)\s*\|\s*(?P<p>P\d|)\s*\|\s*(?P<status>[^|]*?)\s*\|(?P<where>.*)\|\s*$"
)
SCORE_BEGIN = "<!-- score:begin (generated by scripts/check-reliability-register.py) -->"
SCORE_END = "<!-- score:end -->"
LOG_BEGIN = "<!-- burndown:begin (one line per --record) -->"
LOG_END = "<!-- burndown:end -->"


def priority(freq: str, cost: str) -> str:
    """The rule. P1: a researcher will meet it and it costs them something real.

    P1 — high cost met at least sometimes, or med cost met on most projects.
    P2 — high cost but rare; med cost met sometimes; low cost met on most.
    P3 — the rest.
    """
    common = freq in ("every", "most")
    if cost == "high":
        return "P1" if freq != "rare" else "P2"
    if cost == "med":
        if common:
            return "P1"
        return "P2" if freq == "some" else "P3"
    return "P2" if common else "P3"


@dataclass
class Row:
    line_no: int
    rid: str
    cls: str
    freq: str
    cost: str
    p: str
    status: str

    @property
    def state(self) -> str:
        return self.status.split()[0] if self.status else ""


def parse(text: str) -> tuple[list[Row], list[str]]:
    rows: list[Row] = []
    problems: list[str] = []
    for n, line in enumerate(text.splitlines(), 1):
        if not re.match(r"^\|\s*R\d+\s*\|", line):
            continue
        m = ROW.match(line)
        if not m:
            problems.append(f"line {n}: a register row that does not parse: {line[:80]}")
            continue
        r = Row(n, m.group(1), m["cls"].strip(), m["freq"], m["cost"], m["p"], m["status"])
        for part in r.cls.split("/"):
            if part.strip() not in CLASSES:
                problems.append(f"{r.rid}: unknown class {part.strip()!r}")
        if r.freq not in FREQS:
            problems.append(f"{r.rid}: frequency {r.freq!r} is not one of {FREQS}")
        if r.cost not in COSTS:
            problems.append(f"{r.rid}: cost {r.cost!r} is not one of {COSTS}")
        if r.state not in STATUSES:
            problems.append(f"{r.rid}: status {r.status!r} is not one of {STATUSES}")
        if r.state == "fixed" and not re.search(r"\b[0-9a-f]{7,40}\b", r.status):
            problems.append(f"{r.rid}: 'fixed' names no commit")
        rows.append(r)
    seen: dict[str, int] = {}
    for r in rows:
        if r.rid in seen:
            problems.append(f"{r.rid}: id used twice (lines {seen[r.rid]} and {r.line_no})")
        seen[r.rid] = r.line_no
    return rows, problems


def counts(rows: list[Row]) -> dict[str, int]:
    c = {"total": len(rows), "closed": 0, "open": 0, "P1": 0, "P2": 0, "P3": 0,
         "unproven": 0, "decision": 0}
    for r in rows:
        if r.state in OPEN_STATUSES:
            c["open"] += 1
            c[priority(r.freq, r.cost)] += 1
            if r.state in ("unproven", "decision"):
                c[r.state] += 1
        else:
            c["closed"] += 1
    return c


def score_block(rows: list[Row]) -> str:
    c = counts(rows)
    pct = round(100 * c["closed"] / c["total"]) if c["total"] else 0
    return "\n".join([
        SCORE_BEGIN,
        "",
        "| | Open | of which unproven | of which awaiting a decision |",
        "|---|---|---|---|",
        *(
            f"| **{p}** | {c[p]} | "
            f"{sum(1 for r in rows if r.state == 'unproven' and priority(r.freq, r.cost) == p)} | "
            f"{sum(1 for r in rows if r.state == 'decision' and priority(r.freq, r.cost) == p)} |"
            for p in ("P1", "P2", "P3")
        ),
        f"| **All** | {c['open']} | {c['unproven']} | {c['decision']} |",
        "",
        f"**{c['closed']} of {c['total']} closed ({pct}%).**",
        "",
        SCORE_END,
    ])


def log_line(rows: list[Row], today: str) -> str:
    c = counts(rows)
    return (f"| {today} | {c['total']} | {c['closed']} | {c['open']} | "
            f"{c['P1']} | {c['P2']} | {c['P3']} |")


def rewrite(text: str, rows: list[Row], record: bool, today: str) -> str:
    lines = text.splitlines()
    for r in rows:
        want = priority(r.freq, r.cost)
        if r.p != want:
            i = r.line_no - 1
            cells = lines[i].split("|")
            cells[6] = f" {want} "
            lines[i] = "|".join(cells)
    out = "\n".join(lines) + ("\n" if text.endswith("\n") else "")
    out = re.sub(
        re.escape(SCORE_BEGIN) + r".*?" + re.escape(SCORE_END),
        lambda _m: score_block(rows), out, flags=re.S,
    )
    if record:
        def _log(m: re.Match[str]) -> str:
            body = [ln for ln in m.group(1).strip("\n").splitlines()
                    if not ln.startswith(f"| {today} |")]
            body.append(log_line(rows, today))
            return LOG_BEGIN + "\n" + "\n".join(body) + "\n" + LOG_END
        out = re.sub(re.escape(LOG_BEGIN) + r"(.*?)" + re.escape(LOG_END), _log, out, flags=re.S)
    return out


def check(text: str) -> list[str]:
    rows, problems = parse(text)
    if not rows:
        problems.append("no register rows found")
    for r in rows:
        want = priority(r.freq, r.cost)
        if r.p != want:
            problems.append(f"{r.rid}: P cell says {r.p or '(empty)'}, the rule says {want}")
    if SCORE_BEGIN not in text or SCORE_END not in text:
        problems.append("score markers missing")
    else:
        current = text[text.index(SCORE_BEGIN): text.index(SCORE_END) + len(SCORE_END)]
        if current != score_block(rows):
            problems.append("score block is stale — run scripts/check-reliability-register.py --write")
    return problems


def main(argv: list[str]) -> int:
    text = REGISTER.read_text(encoding="utf-8")
    if "--write" in argv or "--record" in argv:
        rows, problems = parse(text)
        if problems:
            print("\n".join(problems))
            return 1
        today = _dt.date.today().isoformat()
        REGISTER.write_text(rewrite(text, rows, "--record" in argv, today), encoding="utf-8")
        text = REGISTER.read_text(encoding="utf-8")
    problems = check(text)
    if problems:
        print("\n".join(problems))
        return 1
    c = counts(parse(text)[0])
    print(f"reliability register: {c['open']} open (P1 {c['P1']}, P2 {c['P2']}, "
          f"P3 {c['P3']}), {c['closed']} of {c['total']} closed")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
