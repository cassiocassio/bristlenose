#!/usr/bin/env python3
"""The Welcome window's session-timeline illustration: one source, two outputs.

The illustration is drawn with the SHIPPED report stylesheet, not a hand-copied
subset of tokens, so its colours and type are the Sessions lens's own. That
stylesheet reaches the app as a generated Swift file:

    desktop/Bristlenose/Bristlenose/WelcomeTimelineCSS.swift

  .venv/bin/python scripts/gen-welcome-timeline.py            # regenerate the Swift file
  .venv/bin/python scripts/gen-welcome-timeline.py --check    # exit 1 if it has drifted
  .venv/bin/python scripts/gen-welcome-timeline.py --mockup   # also rebuild the mockup harness

`tests/test_welcome_timeline.py` runs the `--check` half, so a change to any of
the CSS files below without a regeneration fails the suite rather than leaving
the Welcome picture a release behind the lens it depicts.

`--mockup` rewrites the storyboard-D section of
`docs/mockups/welcome-tapestry-cell.html` (between its D:begin / D:end markers).
It extracts the `timeline` template from `WelcomeIllustrations.swift` and fills
its interpolations the way Swift would, so the harness shows the exact HTML the
app loads — at the Welcome window's real slot sizes — rather than a second copy
of it. Swift-side constants it substitutes are read from the Swift source too.
"""

from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
THEME = REPO / "bristlenose/theme"
SWIFT_DIR = REPO / "desktop/Bristlenose/Bristlenose"
OUT = SWIFT_DIR / "WelcomeTimelineCSS.swift"
MOCKUP = REPO / "docs/mockups/welcome-tapestry-cell.html"

# Cascade order as index.css loads them. Each file is inlined whole, so a reader
# can diff a block against the tree.
FILES = [
    "tokens.css",
    "tokens-typography.css",
    "tokens-desktop.css",
    "colors/palette-default.css",
    "colors/palette-edo.css",
    "atoms/badge.css",
    "organisms/session-tapestry.css",
]


def shipped_css() -> str:
    blocks = []
    for rel in FILES:
        text = (THEME / rel).read_text(encoding="utf-8").rstrip("\n")
        n = text.count("\n") + 1
        blocks.append(f"/* ════ bristlenose/theme/{rel} — lines 1–{n} ════ */\n{text}")
    return "\n\n".join(blocks)


def swift_file() -> str:
    css = shipped_css()
    # A raw string (#"""…"""#): `\(` is not interpolation and `\` is literal, so
    # the CSS goes in byte for byte. Refuse the one sequence that would end it.
    assert '"""#' not in css, "the CSS contains a raw-string terminator"
    return (
        "// GENERATED by scripts/gen-welcome-timeline.py — do not edit by hand.\n"
        "// Regenerate after any change to the files it names; tests/test_welcome_timeline.py\n"
        "// fails while this file and bristlenose/theme/ disagree.\n"
        "//\n"
        "// The shipped report stylesheet for the session timeline, so the Welcome\n"
        "// window's Session timeline illustration (WelcomeIllustrationHTML.timeline)\n"
        "// draws in the Sessions lens's own colours and type rather than a copy of them.\n"
        "\n"
        "enum WelcomeTimelineCSS {\n"
        '    static let shipped = #"""\n'
        f"{css}\n"
        '"""#\n'
        "}\n"
    )


# ── mockup harness ────────────────────────────────────────────────────────────

def _swift_template(name: str) -> str:
    src = (SWIFT_DIR / "WelcomeIllustrations.swift").read_text(encoding="utf-8")
    m = re.search(
        rf"static func {name}\(dark: Bool.*?\n        return \"\"\"\n(?P<body>.*?)\n        \"\"\"",
        src, re.S)
    assert m, f"no `{name}` template in WelcomeIllustrations.swift"
    return m.group("body")


def _curtain() -> str:
    src = (SWIFT_DIR / "WelcomeIllustrations.swift").read_text(encoding="utf-8")
    m = re.search(r"static func curtain\(_ kind: WelcomeIllustration\) -> String \{\n        \"\"\"\n"
                  r"(?P<body>.*?)\n        \"\"\"\n    \}", src, re.S)
    assert m, "no curtain helper"
    return m.group("body")


def _tempo() -> dict[str, float]:
    src = (SWIFT_DIR / "WelcomeBaton.swift").read_text(encoding="utf-8")

    def const(n: str) -> float:
        m = re.search(rf"static let {n}: Double = ([\d.]+)", src)
        assert m, n
        return float(m.group(1))

    return {k: const(k) for k in ("speed", "fadeSeconds", "establishSeconds",
                                  "holdEndSeconds", "restOpacity")}


def _dedent(body: str) -> str:
    # Swift strips the closing delimiter's indentation (8 spaces) from every line.
    return "\n".join(line[8:] if line.startswith("        ") else line.lstrip(" ")
                     for line in body.split("\n"))


def _en(key: str) -> str:
    ns, _, rest = key.partition(".")
    node = json.loads((REPO / f"bristlenose/locales/en/{ns}.json").read_text(encoding="utf-8"))
    for part in rest.split("."):
        node = node[part]
    return node


def timeline_document(dark: bool, palette: str) -> str:
    """The `timeline` template with its interpolations filled as Swift fills them."""
    t = _tempo()
    curtain = _dedent(_curtain())
    curtain = (curtain
               .replace(r"\(WelcomeTempo.jsRestOpacity)", f"{t['restOpacity']:.2f}")
               .replace(r"\(WelcomeTempo.jsFadeMs)", str(int(t["fadeSeconds"] * 1000)))
               .replace(r"\(WelcomeTempo.jsEstablishMs(for: kind))", str(int(t["establishSeconds"] * 1000)))
               .replace(r"\(WelcomeTempo.jsHoldEndMs)", str(int(t["holdEndSeconds"] * 1000))))
    swift_src = (SWIFT_DIR / "WelcomeIllustrations.swift").read_text(encoding="utf-8")
    view = swift_src[swift_src.index("struct TimelineIllustrationView: View"):]
    view = view[: view.index("\n}\n")]
    keys = dict(re.findall(r'"(\w+)": i18n\.t\("([\w.]+)"\)', view))
    assert keys, "TimelineIllustrationView has no strings table"
    strings = {k: _en(v) for k, v in keys.items()}
    js = json.dumps(strings, sort_keys=True, ensure_ascii=False)
    js = js.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    block = (f'<script id="bn-strings" type="application/json">{js}</script>\n'
             '<script>var S=JSON.parse(document.getElementById("bn-strings").textContent);</script>')
    doc = _dedent(_swift_template("timeline"))
    doc = (doc
           .replace(r"\(WelcomeTimelineCSS.shipped)", shipped_css())
           .replace(r'\(dark ? "dark" : "light")', "dark" if dark else "light")
           .replace(r"\(palette)", palette)
           .replace(r'\(reduce ? "1" : "0")', "0")
           .replace(r"\(stringsBlock(strings))", block)
           .replace(r"\(curtain(kind))", curtain)
           .replace(r"\(WelcomeTempo.jsStretch(for: kind))", f"{1 / t['speed']:.3f}"))
    left = re.findall(r"\\\([^)]*\)", doc)
    assert not left, f"unfilled interpolations: {left}"
    return doc.replace("\\\\", "\\")


# The Welcome window's real slot sizes (WelcomeSpiralLayout + the cell chrome).
FRAMES = [
    ("Spiral · window at natural width (760)", 433, 205),
    ("Spiral · 680", 383, 150),
    ("Spiral · narrowest before stacking (600)", 334, 105),
    ("Stacked · 590", 558, 240),
    ("Stacked · narrowest (290)", 258, 240),
]


def mockup_section() -> str:
    # One document; the harness swaps the two attributes the variants differ by,
    # so the page carries the 68 KB stylesheet once rather than four times.
    doc = timeline_document(False, "default")
    assert doc.count('<html data-theme="light" data-color-theme="default"') == 1
    cells = []
    for label, w, h in FRAMES:
        cells.append(
            f'<figure class="dh-frame"><figcaption>{label} · slot {w} × {h}</figcaption>'
            f'<div class="dh-cell" style="width:{w + 32}px">'
            f'<div class="wtag">Study tools</div><div class="wtitle">{html.escape(_en("desktop.welcome.home.tools.timeline.title"))}</div>'
            f'<p class="wline">{html.escape(_en("desktop.welcome.home.tools.timeline.text"))}</p>'
            f'<iframe class="dh-ill" style="width:{w}px;height:{h}px" title="{label}"></iframe>'
            f'<div class="wcta">{html.escape(_en("desktop.welcome.home.tools.timeline.link"))} →</div></div></figure>')
    payload = json.dumps(doc).replace("</", "<\\/")
    return f"""<!-- D:begin — generated by scripts/gen-welcome-timeline.py --mockup; edits here are overwritten -->
  <section class="cand" id="d-harness">
    <h2>D · Unfurl, read, quote <small>— the shipped template, at the Welcome window’s real slot sizes</small></h2>
    <p class="sub">Each frame below loads the exact HTML the app builds (<code>WelcomeIllustrationHTML.timeline</code>), extracted from the Swift source with its interpolations filled. Frames play in turn, like the baton in the app; the dark / Edo buttons at the top rebuild them.</p>
    <div class="dh-grid">{''.join(cells)}</div>
    <div class="com-box wide">
      <p><span class="verdict">What is shipped CSS and what is liberty.</span> Colours, type, lanes, flags, marks, theme spans, ticks and the popover are <code>session-tapestry.css</code>, <code>badge.css</code> and the tokens, inlined verbatim through <code>WelcomeTimelineCSS.swift</code> (a generated file with a drift test). The scale rule is the lens’s own: fit the session to the width, held between 1 and 4 s/px, so a 40-minute interview draws as slivers and scrolls sideways in every frame narrower than about 700 logical px.</p>
      <ul>
        <li><strong>Liberties, each to fit.</strong> One theme row (the lens packs three). 34 pt of air above and below the sentiment axis (the lens uses 41 and 40). A one-row crop of the Sessions grid stands in for the real row. The scrollbar is drawn, because a programmatic scroll does not reliably show macOS’s overlay bar. The whole picture scales down, never up, when the slot is shorter than its natural height; the logical width grows by the same factor, so a short slot shows more of the session rather than a smaller copy of the same crop.</li>
        <li><strong>Read beat.</strong> One stop per section; the playhead sits, the tick nearest it turns blue, that section’s flag rises in full and holds for 0.8 s (absolute, not stretched by the group tempo). When the next stop is off-screen the timeline scrolls under the pointer.</li>
        <li><strong>Quote.</strong> A Delight mark in the last section, so the popover opens above the axis line and overlays the Themes lane, as in the lens.</li>
      </ul>
    </div>
  </section>
  <script>
  (function(){{
    var DOC={payload};
    var frames=[].slice.call(document.querySelectorAll("#d-harness .dh-ill")), turn=0, gen=0;
    function variant(){{ var r=document.documentElement;
      return DOC.replace('<html data-theme="light" data-color-theme="default"',
        '<html data-theme="'+(r.getAttribute("data-scheme")==="dark"?"dark":"light")+'" data-color-theme="'+(r.getAttribute("data-color-theme")==="edo"?"edo":"default")+'"'); }}
    function load(){{
      gen++; var mine=gen, ready=0;
      frames.forEach(function(f){{ f.onload=function(){{ ready++; if(ready===frames.length && mine===gen) start(mine); }}; f.srcdoc=variant(); }});
    }}
    function start(mine){{
      frames.forEach(function(f){{ f.contentWindow.webkit={{messageHandlers:{{bn:{{postMessage:function(){{ if(mine!==gen) return; f.contentWindow.BN.setActive(false); turn=(turn+1)%frames.length; setTimeout(function(){{ if(mine===gen) play(); }}, 1200); }}}}}}}}; }});
      play();
      function play(){{ frames[turn].contentWindow.BN.setActive(true); }}
    }}
    ["scheme","palette"].forEach(function(id){{ var b=document.getElementById(id); if(b) b.addEventListener("click", function(){{ setTimeout(load, 0); }}); }});
    load();
  }})();
  </script>
<!-- D:end -->"""


HARNESS_CSS = """
/* D harness */
.dh-grid { display: flex; flex-wrap: wrap; gap: 20px 24px; align-items: flex-start; margin-bottom: 16px; }
.dh-frame { margin: 0; }
.dh-frame figcaption { font: 11px ui-monospace, Menlo, monospace; color: light-dark(#777, #999); margin-bottom: 6px; }
.dh-cell { padding: 14px 16px 16px; border-radius: 10px; border: 1px solid light-dark(#c8c8c8, #444);
  background: light-dark(color-mix(in srgb, #fff 94%, #3b6fd9), color-mix(in srgb, #262626 90%, #5a86e0)); box-sizing: border-box; }
.dh-ill { display: block; border: 0; background: transparent; outline: 1px dashed light-dark(rgba(0,0,0,.12), rgba(255,255,255,.15)); }
"""


def write_mockup() -> None:
    page = MOCKUP.read_text(encoding="utf-8")
    begin, end = "<!-- D:begin", "<!-- D:end -->"
    assert page.count(begin) == 1 and page.count(end) == 1, "mockup has lost its D markers"
    a = page.index(begin)
    b = page.index(end) + len(end)
    page = page[:a] + mockup_section() + page[b:]
    if "/* D harness */" not in page:
        page = page.replace("</style>", HARNESS_CSS + "</style>", 1)
    MOCKUP.write_text(page, encoding="utf-8")
    print(f"wrote {MOCKUP.relative_to(REPO)} ({len(page):,} bytes)")


def main(argv: list[str]) -> int:
    want = swift_file()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != want:
            print(f"{OUT.relative_to(REPO)} is out of date — run scripts/gen-welcome-timeline.py")
            return 1
        return 0
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != want:
        OUT.write_text(want, encoding="utf-8")
        print(f"wrote {OUT.relative_to(REPO)} ({len(want):,} bytes)")
    if "--mockup" in argv:
        write_mockup()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
