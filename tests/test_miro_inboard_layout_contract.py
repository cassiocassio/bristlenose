"""Python side of the in-Miro app's layout contract.

The in-Miro app (`miro-app/`) draws a board file inside Miro and must lay it out
exactly as Send to Miro does, so a tester's feedback on the REST board holds for
the in-board one (`docs/design-miro-in-board-app.md`). This test lays out the
board-file fixture's own columns with `board_layout.layout_board` and writes what
Send to Miro would send: every sticky's box, colour and content, the frames, and
the title text. `miro-app/src/layout.test.ts` plans `figjam-board-v1.json` and must
arrive at the same numbers, so a change on either side fails one of the two.

Generated, never hand-edited. After a deliberate layout change:

    BRISTLENOSE_REGENERATE_BOARD_FIXTURE=1 .venv/bin/python -m pytest tests/test_miro_inboard_layout_contract.py
"""

from __future__ import annotations

import json
import os
from html import escape
from pathlib import Path
from typing import Any

from bristlenose.board_layout import STICKY_SHAPES, layout_board
from bristlenose.server.miro_export import _sticky_content
from tests.test_board_fixture_contract import FIXTURE_TITLE, _columns

LAYOUT = Path(__file__).resolve().parent / "fixtures" / "miro-inboard-layout-v1.json"
#: `board_layout.text_width` counts a character East Asian Wide or Fullwidth as two. JavaScript has
#: no `unicodedata`, so the app carries Python's own table, generated here.
WIDE_TS = Path(__file__).resolve().parents[1] / "miro-app" / "src" / "eastAsianWide.ts"


def _wide_ranges() -> list[tuple[int, int]]:
    import sys
    import unicodedata

    out: list[tuple[int, int]] = []
    for cp in range(sys.maxunicode + 1):
        if unicodedata.east_asian_width(chr(cp)) in "WF":
            if out and out[-1][1] == cp - 1:
                out[-1] = (out[-1][0], cp)
            else:
                out.append((cp, cp))
    return out


def _wide_ts() -> str:
    import unicodedata

    rows = ",\n".join(f"  [0x{a:X}, 0x{b:X}]" for a, b in _wide_ranges())
    return (
        "// Generated by tests/test_miro_inboard_layout_contract.py from Python's unicodedata\n"
        f"// (Unicode {unicodedata.unidata_version}). Do not edit: regenerate, as that file says.\n"
        "// Code points whose East Asian Width is W or F, which board_layout.text_width counts as two.\n"
        f"export const EAST_ASIAN_WIDE: ReadonlyArray<readonly [number, number]> = [\n{rows},\n];\n"
    )


def _r(v: float) -> float:
    return round(v, 3)


def _layout(shape: str) -> dict[str, Any]:
    board = layout_board(_columns(), FIXTURE_TITLE, shape=shape)
    (title,) = board.texts
    return {
        "shape": shape,
        "width": _r(board.width),
        "height": _r(board.height),
        # As `miro_export._push` sends it: centre x is the text's left + 300, width 600.
        "title": {"content": escape(title.text), "x": _r(title.x + 300), "y": _r(title.y),
                  "width": 600, "font_size": int(title.size)},
        # Top-left corners; Miro wants centres, which the app works out.
        "frames": [{"title": f.title, "x": _r(f.x), "y": _r(f.y), "width": _r(f.width),
                    "height": _r(f.height)} for f in board.frames],
        "stickies": [{"kind": s.kind, "x": _r(s.x), "y": _r(s.y), "width": _r(s.width),
                      "height": _r(s.height), "colour": s.colour, "set": s.set_id,
                      "content": _sticky_content(s, "en")} for s in board.stickies],
    }


def _expected() -> str:
    doc = {"shapes": {shape: _layout(shape) for shape in STICKY_SHAPES}}
    return json.dumps(doc, ensure_ascii=True, indent=1) + "\n"


if os.environ.get("BRISTLENOSE_REGENERATE_BOARD_FIXTURE") == "1":
    LAYOUT.write_text(_expected(), encoding="utf-8")
    WIDE_TS.parent.mkdir(parents=True, exist_ok=True)
    WIDE_TS.write_text(_wide_ts(), encoding="utf-8")


def test_the_apps_wide_character_table_is_pythons() -> None:
    """Checked only on a Python with the same Unicode version the table was made from: CI runs
    3.10 to 3.13, whose `unicodedata` differ, and the table is pinned to one of them."""
    import unicodedata

    import pytest

    text = WIDE_TS.read_text(encoding="utf-8")
    if f"(Unicode {unicodedata.unidata_version})" not in text:
        pytest.skip(f"table made from another Unicode version than {unicodedata.unidata_version}")
    assert text == _wide_ts(), (
        "miro-app/src/eastAsianWide.ts is not this Python's East Asian Width table; regenerate."
    )


def test_the_layout_is_what_send_to_miro_sends() -> None:
    assert LAYOUT.read_text(encoding="utf-8") == _expected(), (
        "board_layout or miro_export no longer lays the fixture out as "
        "tests/fixtures/miro-inboard-layout-v1.json says. If deliberate, regenerate "
        "(see this file's docstring), read the diff, and run miro-app's tests."
    )


def test_the_layout_exercises_split_sets_and_a_clip_link() -> None:
    doc = json.loads(LAYOUT.read_text(encoding="utf-8"))
    for shape in STICKY_SHAPES:
        stickies = doc["shapes"][shape]["stickies"]
        assert {s["set"] for s in stickies} - {None}, "no split quote in the fixture"
        assert any("<a href=" in s["content"] for s in stickies), "no clip link"
        assert sum(s["kind"] == "header" for s in stickies) == 3
